def force_ipv4_resolution():
    orig_getaddrinfo = socket.getaddrinfo

    def ipv4_only(host, *args, **kwargs):
        return orig_getaddrinfo(host, socket.AF_INET, *args, **kwargs)

    socket.getaddrinfo = ipv4_only

force_ipv4_resolution()
